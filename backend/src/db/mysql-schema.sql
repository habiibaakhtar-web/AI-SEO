CREATE TABLE IF NOT EXISTS app_migrations (name VARCHAR(100) PRIMARY KEY, applied_at DATETIME(3) DEFAULT CURRENT_TIMESTAMP(3)) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS users (
 id CHAR(36) CHARACTER SET ascii PRIMARY KEY, name VARCHAR(100) NOT NULL,
 email VARCHAR(254) NOT NULL UNIQUE, password_hash VARCHAR(255) NOT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS websites (
 id CHAR(36) CHARACTER SET ascii PRIMARY KEY, user_id CHAR(36) CHARACTER SET ascii NOT NULL,
 name VARCHAR(100) NOT NULL, url TEXT NOT NULL, description TEXT NOT NULL,
 url_hash CHAR(64) CHARACTER SET ascii GENERATED ALWAYS AS (SHA2(url,256)) STORED,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 UNIQUE KEY websites_owner_url (user_id,url_hash), FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS audits (
 id CHAR(36) CHARACTER SET ascii PRIMARY KEY, website_id CHAR(36) CHARACTER SET ascii NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'queued', overall_score SMALLINT, technical_score SMALLINT, on_page_score SMALLINT, content_score SMALLINT,
 scoring_version VARCHAR(255), coverage JSON NOT NULL DEFAULT ('{}'), error_code VARCHAR(255), completed_at DATETIME(3),
 recommendation_status VARCHAR(30) NOT NULL DEFAULT 'pending', progress TEXT NOT NULL, target_url TEXT NOT NULL,
 lease_expires_at DATETIME(3), lease_owner CHAR(36) CHARACTER SET ascii,
 active_website CHAR(36) CHARACTER SET ascii DEFAULT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 UNIQUE KEY audits_one_active (active_website), INDEX audits_website_created (website_id,created_at),
 FOREIGN KEY (website_id) REFERENCES websites(id) ON DELETE CASCADE,
 CHECK(status IN ('queued','running','completed','failed','cancelled'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS crawled_pages (
 id CHAR(36) CHARACTER SET ascii PRIMARY KEY, audit_id CHAR(36) CHARACTER SET ascii NOT NULL,
 url TEXT NOT NULL, http_status SMALLINT, evidence JSON NOT NULL DEFAULT ('{}'),
 url_hash CHAR(64) CHARACTER SET ascii GENERATED ALWAYS AS (SHA2(url,256)) STORED,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 UNIQUE KEY crawled_audit_url (audit_id,url_hash), FOREIGN KEY (audit_id) REFERENCES audits(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS seo_issues (
 id CHAR(36) CHARACTER SET ascii PRIMARY KEY, audit_id CHAR(36) CHARACTER SET ascii NOT NULL,
 title TEXT NOT NULL, category VARCHAR(20) NOT NULL, severity VARCHAR(20) NOT NULL, description TEXT NOT NULL,
 why_it_matters TEXT NOT NULL, recommendation TEXT NOT NULL, page_url TEXT NOT NULL, check_id VARCHAR(255) NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'open', evidence JSON NOT NULL DEFAULT ('{}'),
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 UNIQUE KEY issues_id_audit (id,audit_id), INDEX issues_audit_status (audit_id,status),
 FOREIGN KEY (audit_id) REFERENCES audits(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS recommendations (
 id CHAR(36) CHARACTER SET ascii PRIMARY KEY, audit_id CHAR(36) CHARACTER SET ascii NOT NULL, issue_id CHAR(36) CHARACTER SET ascii NOT NULL,
 recommendation TEXT NOT NULL, reason TEXT NOT NULL, priority VARCHAR(20) NOT NULL, suggested_text TEXT,
 source VARCHAR(10) NOT NULL DEFAULT 'ai', created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 FOREIGN KEY (audit_id) REFERENCES audits(id) ON DELETE CASCADE,
 FOREIGN KEY (issue_id,audit_id) REFERENCES seo_issues(id,audit_id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS sessions (
 id CHAR(36) CHARACTER SET ascii PRIMARY KEY, user_id CHAR(36) CHARACTER SET ascii NOT NULL,
 expires_at DATETIME(3) NOT NULL, created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 INDEX sessions_user (user_id), FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS password_resets (
 token_hash CHAR(64) CHARACTER SET ascii PRIMARY KEY, user_id CHAR(36) CHARACTER SET ascii NOT NULL, expires_at DATETIME(3) NOT NULL,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS keywords (
 id CHAR(36) CHARACTER SET ascii PRIMARY KEY, website_id CHAR(36) CHARACTER SET ascii NOT NULL,
 keyword VARCHAR(200) NOT NULL, category VARCHAR(100) NOT NULL DEFAULT '', intent VARCHAR(20) NOT NULL DEFAULT 'informational',
 priority VARCHAR(10) NOT NULL DEFAULT 'medium', target_page TEXT NOT NULL, status VARCHAR(20) NOT NULL DEFAULT 'planned', notes TEXT NOT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 FOREIGN KEY (website_id) REFERENCES websites(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS content_items (
 id CHAR(36) CHARACTER SET ascii PRIMARY KEY, website_id CHAR(36) CHARACTER SET ascii NOT NULL,
 kind VARCHAR(20) NOT NULL, input JSON NOT NULL, output JSON NOT NULL, source VARCHAR(10) NOT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), INDEX content_website_created (website_id,created_at),
 FOREIGN KEY (website_id) REFERENCES websites(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
